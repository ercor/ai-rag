"""Ollama-based Generator adapter.

Streams answer tokens from the Ollama /api/generate endpoint
using the configured model (default: qwen2.5).
"""

import logging
from typing import AsyncIterator

import httpx

from src.config import get_settings

logger = logging.getLogger(__name__)


class OllamaGenerator:
    """Generates answer tokens by streaming from Ollama.

    Implements the Generator port protocol.
    Uses the /api/generate endpoint with stream=true for token-by-token output.
    """

    def __init__(
        self,
        base_url: str | None = None,
        model: str | None = None,
    ):
        settings = get_settings()
        self.base_url = (base_url or settings.ollama_base_url).rstrip("/")
        self.model = model or settings.ollama_model

    async def generate_stream(self, prompt: str) -> AsyncIterator[str]:
        """Yield answer tokens as they are generated by the LLM.

        Sends the prompt to Ollama's /api/generate endpoint with streaming
        enabled. Each response chunk contains a "response" field with the
        generated token(s).

        Raises:
            httpx.HTTPStatusError: If Ollama returns a non-200 status.
            httpx.RequestError: If the connection to Ollama fails.
        """
        url = f"{self.base_url}/api/generate"
        payload = {
            "model": self.model,
            "prompt": prompt,
            "stream": True,
            "options": {
                "temperature": 0.1,
                "num_predict": 512,
            },
        }

        logger.debug(
            "Starting generation stream: model=%s, prompt_len=%d",
            self.model,
            len(prompt),
        )

        async with httpx.AsyncClient(timeout=120.0) as client:
            async with client.stream("POST", url, json=payload) as response:
                response.raise_for_status()

                async for line in response.aiter_lines():
                    if not line.strip():
                        continue

                    # Ollama streaming returns JSON objects, one per line
                    import json

                    try:
                        data = json.loads(line)
                    except json.JSONDecodeError:
                        logger.warning("Skipping non-JSON line from Ollama: %s", line[:100])
                        continue

                    # Check for done signal
                    if data.get("done", False):
                        logger.debug("Generation stream complete")
                        break

                    # Extract the token
                    token = data.get("response", "")
                    if token:
                        yield token

        logger.debug("Generation stream finished for model=%s", self.model)
